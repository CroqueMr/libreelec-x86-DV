/* Exercise the real HEVC decoder without requiring a VA display. Only the
 * format tag is substituted, leaving the pixels and timestamps untouched. */
static int software_receive(AVCodecContext *decoder, AVFrame *frame)
{
    int result = avcodec_receive_frame(decoder, frame);
    if (result == 0)
        frame->format = AV_PIX_FMT_VAAPI;
    return result;
}
#define avcodec_receive_frame software_receive
#include "dvbridge_fel.c"
#undef avcodec_receive_frame

