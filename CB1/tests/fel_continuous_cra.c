static void check(unsigned length_size, bool missing_el)
{
    const unsigned size[] = {270, 36, 63, 37, 34};
    const int display_order[] = {0, 2, 1, 4, 3};
    AVCodecParameters *parameters = avcodec_parameters_alloc();
    assert(parameters);
    parameters->codec_type = AVMEDIA_TYPE_VIDEO;
    parameters->codec_id = AV_CODEC_ID_HEVC;
    parameters->video_delay = 1; /* Reported by the demuxer for this reordered BL. */
    if (length_size) {
        /* Matroska can supply separate hvcC for the EL while the BL is Annex-B. */
        AVPacketSideData *conf = av_packet_side_data_new(&parameters->coded_side_data,
            &parameters->nb_coded_side_data, AV_PKT_DATA_HEVC_CONF, 23, 0);
        assert(conf);
        memset(conf->data, 0, conf->size);
        conf->data[0] = 1;
        conf->data[21] = 0xfc | (length_size - 1);
    }
    struct dvbridge_fel *fel = dvbridge_fel_create(parameters, (AVRational){1, 24});
    avcodec_parameters_free(&parameters);
    assert(fel);
    fel->decoder->get_format = avcodec_default_get_format;
    assert(avcodec_open2(fel->decoder, fel->decoder->codec, NULL) == 0);
    fel->opened = true;
    AVPacket *packet = av_packet_alloc();
    assert(packet);
    unsigned offset = 0;
    for (size_t i = 0; i < sizeof(size) / sizeof(*size); ++i) {
        /* AU 1's first 17 bytes are its BL alone. */
        unsigned bytes = missing_el && i == 1 ? 17 : size[i];
        assert(av_new_packet(packet, bytes) == 0);
        memcpy(packet->data, paired + offset, bytes);
        offset += size[i];
        packet->dts = i;
        packet->pts = 100 + display_order[i];
        assert(dvbridge_fel_submit(fel, packet));
        av_packet_unref(packet);
    }
    assert(offset == sizeof(paired));
    bool drained = dvbridge_fel_drain(fel, NULL);
    if (!missing_el)
        assert(drained);
    for (int i = 0; i < 5; ++i) {
        AVFrame *frame = NULL;
        int result = dvbridge_fel_take(fel, 100 + i, &frame);
        if (missing_el && i > 0) {
            assert(result != 1 && !frame);
        } else {
            assert(result == 1 && frame->pts == 100 + i);
            assert(frame->data[0][0] == 32 + 24 * i);
            av_frame_free(&frame);
        }
    }
    av_packet_free(&packet);
    dvbridge_fel_destroy(fel);
}

int main(void)
{
    if (!avcodec_find_decoder(AV_CODEC_ID_HEVC))
        return 77;
    for (unsigned length_size = 0; length_size <= 4; ++length_size) {
        check(length_size, false);
        check(length_size, true);
    }
    return 0;
}
