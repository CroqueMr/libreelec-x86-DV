"""Print deterministic C witnesses calculated by the independent integer oracle."""
import random
from dovi_master_reference import reshape_component, nlq_residual, reconstruct

rng=random.Random(1729)
print('/* SPDX-License-Identifier: GPL-3.0-or-later */')
print('/* Generated by reference/generate_master_vectors.py. */')
print('static const struct master_vector { int method, order, depth, bl[3], el; int64_t coeff[22]; unsigned expected; } master_vectors[] = {')
for index in range(128):
    method=index%2
    order=2 if not method else 1+(index//2)%3
    bl=[rng.randrange(1024) for _ in range(3)]
    depth=10 if index%4==0 else 12
    coeff=[0]*22
    if not method:
        if index%8==0:
            # Wide signed cancellation with low coefficient bits intact.
            coeff[:3]=[(bl[0]<<22)+(1<<21)+rng.randrange(32),-(1<<32),0]
        else:
            coeff[:3]=[rng.randrange(-(1<<21),1<<22),rng.randrange(-(1<<23),2<<23),rng.randrange(-(1<<23),1<<23)]
    else:
        coeff[0]=1<<22
        coeff[1:1+7*order]=[rng.randrange(-(1<<23),1<<23) for _ in range(7*order)]
    curves=[{'pivots':[0,1023],'method':[0],'order':[1],'poly':[[0,1<<23,0]]} for _ in range(3)]
    c=1 if method else 0
    curves[c]={'pivots':[0,1023],'method':[method],'order':[order],
        'poly':[coeff[:3]],'mmr_constant':[coeff[0]],
        'mmr':[[coeff[1+i*7:8+i*7] for i in range(3)]]}
    q={'offset':512,'slope':8192,'threshold':4096,'maximum':131072}
    data={'bl_depth':10,'el_depth':10,'denom':23,'curves':curves,'residual':True,'nlq':[q]*3}
    e=512 if index%11==0 else rng.randrange(1024)
    expected=reconstruct(reshape_component(data,c,bl),nlq_residual(data,c,e),depth)
    print('{'+f'{method},{order},{depth},'+'{'+','.join(map(str,bl))+'},'+str(e)+',{' +
          ','.join('INT64_C('+str(v)+')' for v in coeff)+'},'+str(expected)+'},')
print('};')
